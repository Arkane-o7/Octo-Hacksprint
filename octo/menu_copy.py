def copy(key, language):
    text = COPY.get(language.split('-')[0], COPY['en'])[key]
    if key == 'languages':
        return text.format(choices='\n'.join(f'{number} · {label}' for number, (_, label) in LANGUAGES.items()))
    return text


def menu_language(text, parent):
    for start, end, language in (
        ('\u0b80', '\u0bff', 'ta-IN'), ('\u0c00', '\u0c7f', 'te-IN'),
        ('\u0980', '\u09ff', 'bn-IN'), ('\u0a80', '\u0aff', 'gu-IN'),
    ):
        if any(start <= c <= end for c in text):
            return language
    if any('\u0900' <= c <= '\u097f' for c in text):
        # Hindi and Marathi share a script; keep the saved Marathi preference.
        return 'mr-IN' if parent.get('language') == 'mr-IN' else 'hi-IN'
    if any(c.isascii() and c.isalpha() for c in text):
        return 'en-IN'
    return parent.get('language', 'en-IN')
